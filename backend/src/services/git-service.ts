import { simpleGit, SimpleGit, SimpleGitOptions } from "simple-git";
import path from "path";
import { Platform, getPlatformDirectoryName } from "@codesync/shared";

export interface CommitOptions {
  repoRoot: string;
  filesToStage: string[];
  message: string;
  autoPush?: boolean;
}

export interface CommitResult {
  commitHash: string;
  pushed: boolean;
  pushFailed?: boolean;
  pushError?: string;
}

export class GitError extends Error {
  constructor(message: string, public readonly cause?: unknown) {
    super(message);
    this.name = "GitError";
  }
}

/**
 * Builds a SimpleGit instance pointed at the given repo root.
 */
function getGit(repoRoot: string): SimpleGit {
  const options: Partial<SimpleGitOptions> = {
    baseDir: repoRoot,
    binary: "git",
    maxConcurrentProcesses: 1,
    trimmed: false,
  };
  return simpleGit(options);
}

/**
 * Validates that the given path is a valid Git working tree.
 * Throws GitError if not.
 */
export async function validateGitRepo(repoRoot: string): Promise<void> {
  const git = getGit(repoRoot);
  try {
    const isRepo = await git.checkIsRepo();
    if (!isRepo) {
      throw new GitError(`"${repoRoot}" is not a Git repository.`);
    }
  } catch (err) {
    if (err instanceof GitError) throw err;
    throw new GitError(`Failed to validate Git repository at "${repoRoot}"`, err);
  }
}

/**
 * Returns the current Git status summary for the repo.
 */
export async function getGitStatus(repoRoot: string) {
  const git = getGit(repoRoot);
  try {
    return await git.status();
  } catch (err) {
    throw new GitError(`Failed to get Git status at "${repoRoot}"`, err);
  }
}

/**
 * Stages ONLY the specified files relative to the repo root.
 * Never runs `git add .` — only stages the exact files generated by CodeSync.
 *
 * Security: all file paths must be verified to be inside repoRoot before calling.
 */
export async function stageFiles(repoRoot: string, filePaths: string[]): Promise<void> {
  if (filePaths.length === 0) {
    throw new GitError("No files provided to stage.");
  }

  const git = getGit(repoRoot);
  const absoluteRoot = path.resolve(repoRoot);

  // Convert to relative paths for git add (more portable)
  const relativePaths = filePaths.map((fp) => {
    const abs = path.resolve(fp);
    if (!abs.startsWith(absoluteRoot + path.sep) && abs !== absoluteRoot) {
      throw new GitError(
        `Refusing to stage file outside repo root: "${fp}"`
      );
    }
    return path.relative(absoluteRoot, abs);
  });

  try {
    await git.add(relativePaths);
  } catch (err) {
    throw new GitError(`Failed to stage files: ${relativePaths.join(", ")}`, err);
  }
}

/**
 * Creates a Git commit with the provided message.
 * Only commits if there are staged changes.
 * Returns the commit hash.
 */
export async function createCommit(repoRoot: string, message: string): Promise<string> {
  const git = getGit(repoRoot);

  try {
    const status = await git.status();
    if (status.staged.length === 0) {
      throw new GitError("No staged changes to commit.");
    }

    const result = await git.commit(message);
    const hash = result.commit;

    if (!hash) {
      throw new GitError("Commit succeeded but no commit hash was returned.");
    }

    return hash;
  } catch (err) {
    if (err instanceof GitError) throw err;
    throw new GitError(`Failed to create commit: ${message}`, err);
  }
}

/**
 * Pushes the current branch to the configured remote.
 * If the push fails, the error is returned (not thrown) so the job
 * can be marked as push-failed/retryable without losing the local commit.
 */
export async function pushToRemote(repoRoot: string): Promise<{ pushed: boolean; error?: string }> {
  const git = getGit(repoRoot);

  try {
    // First try a plain push (works when upstream tracking is already set)
    await git.push();
    return { pushed: true };
  } catch (firstErr: any) {
    const msg = firstErr?.message || String(firstErr);
    // If no upstream is configured, set it and push explicitly to origin main/master
    if (
      msg.includes("no upstream") ||
      msg.includes("has no upstream") ||
      msg.includes("set-upstream") ||
      msg.includes("The current branch") ||
      msg.includes("does not track")
    ) {
      try {
        // Detect default branch name
        const status = await git.status();
        const branch = status.current || "main";
        await git.push(["-u", "origin", branch]);
        return { pushed: true };
      } catch (retryErr: any) {
        return { pushed: false, error: retryErr?.message || String(retryErr) };
      }
    }
    return { pushed: false, error: msg };
  }
}

/**
 * Builds the commit message from a template.
 * Default format: feat(leetcode): add Two-Sum
 */
export function buildCommitMessage(
  platform: Platform,
  problemTitle: string,
  template = "feat({platform}): add {problem}"
): string {
  const platformLabel = getPlatformDirectoryName(platform).toLowerCase();
  const sanitizedTitle = problemTitle
    .replace(/[^\w\s-]/g, "")
    .trim()
    .replace(/\s+/g, "-");

  return template
    .replace("{platform}", platformLabel)
    .replace("{problem}", sanitizedTitle);
}

/**
 * High-level: stage + commit + optional push.
 * Failure modes:
 *  - Stage/commit failure: throws GitError (job should be retried)
 *  - Push failure: returns result with pushed=false, pushError set (local commit preserved)
 */
export async function commitFiles(options: CommitOptions): Promise<CommitResult> {
  const { repoRoot, filesToStage, message, autoPush = false } = options;

  await stageFiles(repoRoot, filesToStage);
  const commitHash = await createCommit(repoRoot, message);

  if (!autoPush) {
    return { commitHash, pushed: false };
  }

  const pushResult = await pushToRemote(repoRoot);

  return {
    commitHash,
    pushed: pushResult.pushed,
    pushFailed: !pushResult.pushed,
    pushError: pushResult.error,
  };
}
