import { SolutionSubmission, getLanguageExtension, ExplanationOutput } from "@codesync/shared";

/**
 * Renders a placeholder README before OpenAI explanation is available.
 * This is the Phase 3 version — a clean, well-formatted initial README
 * that will be replaced/enriched in Phase 5 with AI-generated content.
 */
export function renderInitialReadme(submission: SolutionSubmission): string {
  const { platform, problem, submission: sub } = submission;
  const ext = getLanguageExtension(sub.language);

  const platformLabel = platform === "leetcode" ? "LeetCode" : "GeeksForGeeks";
  const difficultyBadge = problem.difficulty
    ? `**Difficulty:** ${problem.difficulty}`
    : "";

  const statementSection = problem.statement
    ? `\n## Problem Statement\n\n${problem.statement.trim()}\n`
    : "";

  const lines = [
    `# ${problem.title}`,
    ``,
    `| Field | Value |`,
    `|-------|-------|`,
    `| Platform | ${platformLabel} |`,
    ...(problem.difficulty ? [`| Difficulty | ${problem.difficulty} |`] : []),
    `| Language | ${sub.language} |`,
    `| URL | [${problem.url}](${problem.url}) |`,
    `| Submitted | ${sub.submittedAt} |`,
    ``,
    statementSection,
    `## Solution`,
    ``,
    `\`\`\`${langCodeFence(sub.language)}`,
    sub.code,
    `\`\`\``,
    ``,
    `---`,
    ``,
    `*Explanation generated by CodeSync — AI explanation will be added once the OpenAI service is enabled.*`,
  ];

  return lines.join("\n");
}

/**
 * Renders the full AI-enhanced README from structured explanation output.
 * Called in Phase 5 when OpenAI service is available.
 */
export function renderExplainedReadme(
  submission: SolutionSubmission,
  explanation: ExplanationOutput
): string {
  const { platform, problem, submission: sub } = submission;
  const platformLabel = platform === "leetcode" ? "LeetCode" : "GeeksForGeeks";

  const statementSection = problem.statement
    ? `\n## 📝 Problem Statement\n\n${problem.statement.trim()}\n`
    : "";

  const analogySection = explanation.analogy
    ? `\n### 💡 Real-World Analogy\n> ${explanation.analogy}\n`
    : "";

  const mermaidSection = explanation.mermaid_diagram
    ? `\n## 📊 Visual Algorithm Flowchart\n\n\`\`\`mermaid\n${explanation.mermaid_diagram.trim()}\n\`\`\`\n`
    : "";

  const dryRunSection = explanation.visual_dry_run
    ? `\n## 🔍 Visual Step-by-Step Dry Run\n\n\`\`\`text\n${explanation.visual_dry_run.trim()}\n\`\`\`\n`
    : "";

  const edgeCasesSection =
    explanation.edge_cases && explanation.edge_cases.length > 0
      ? `\n## ⚠️ Edge Cases\n\n${explanation.edge_cases.map((c) => `- [x] ${c}`).join("\n")}`
      : "";

  return [
    `# ${problem.title}`,
    ``,
    `| Field | Value |`,
    `|-------|-------|`,
    `| Platform | ${platformLabel} |`,
    ...(problem.difficulty ? [`| Difficulty | ${problem.difficulty} |`] : []),
    `| Language | ${sub.language} |`,
    `| URL | [${problem.url}](${problem.url}) |`,
    `| Submitted | ${sub.submittedAt} |`,
    ``,
    statementSection,
    `## 🧠 Approach & Intuition`,
    ``,
    `**Core Concept:** ${explanation.approach}`,
    ``,
    explanation.intuition,
    analogySection,
    mermaidSection,
    dryRunSection,
    `## 🪜 Step-by-Step Logic`,
    ``,
    explanation.step_by_step,
    ``,
    `## 🎯 Invariant & Correctness`,
    ``,
    explanation.why_it_works,
    ``,
    `## ⏱️ Complexity Analysis`,
    ``,
    `| Metric | Complexity | Explanation |`,
    `|--------|------------|-------------|`,
    `| **Time Complexity** | \`${explanation.time_complexity}\` | Optimal for this constraint |`,
    `| **Space Complexity** | \`${explanation.space_complexity}\` | Auxiliary memory used |`,
    ``,
    edgeCasesSection,
    ``,
    `## 💻 Solution Code`,
    ``,
    `\`\`\`${langCodeFence(sub.language)}`,
    sub.code,
    `\`\`\``,
    ``,
    `---`,
    `*Automated sync & diagrammatic documentation by [CodeSync](https://github.com/ALLENKISAIRAKESH/My_Solved_Problems_CodeSync)*`,
  ]
    .join("\n")
    .trim();
}

function langCodeFence(language: string): string {
  const fenceMap: Record<string, string> = {
    python3: "python",
    python: "python",
    cpp: "cpp",
    "c++": "cpp",
    c: "c",
    java: "java",
    javascript: "javascript",
    js: "javascript",
    typescript: "typescript",
    ts: "typescript",
    golang: "go",
    go: "go",
    rust: "rust",
    csharp: "csharp",
    "c#": "csharp",
    kotlin: "kotlin",
    swift: "swift",
    ruby: "ruby",
    scala: "scala",
    php: "php",
    bash: "bash",
    sql: "sql",
  };
  return fenceMap[language.toLowerCase()] || language.toLowerCase();
}
